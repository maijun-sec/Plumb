package org.plumb.main;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;

/**
 * The retired rule ids, and the rule each of them names today.
 *
 * <p>A rule id is not a stable name. The engine renamed its rules when the id scheme changed — the
 * {@code plumb.<domain>.<name>} scheme became the {@code <engine>-<domain>-<name>} scheme — and the
 * per-CWE configurations in the project were written against the OLD ids. Those configurations are
 * still the authority on WHICH rule is about WHICH CWE, so the old ids have to keep working.
 *
 * <p><b>Why this matters.</b> Without the map, a configuration entry naming an old id selected
 * NOTHING: the rule never fired, the CWE's recall read 0, and nothing said so. That is the worst
 * kind of failure — a silent one that reads as "this code is clean". The measurement was not
 * measuring the rule; it was measuring the filter.
 *
 * <p>The map is a resource ({@code legacy-rule-aliases.json}) rather than code, because it is DATA:
 * it is derived from the recorded rule-id migration and the live rule registry, and it is
 * regenerated by {@code scripts/generate_legacy_rule_aliases.py}. Hand-writing it would put a
 * second source of truth next to the registry, and the two would drift.
 *
 * <p>The resource is plain JSON with no comments, because a JSON parser has to be able to read it.
 * The prose lives here, next to the code that consults it.
 *
 * <p>The map is loaded once, lazily, and is immutable afterwards.
 */
final class LegacyRuleAliases {

  private static final String RESOURCE = "/legacy-rule-aliases.json";

  /**
   * The map, loaded lazily.
   *
   * <p>Loading is deferred to first use so that a scan that never consults the map pays nothing,
   * and so a missing or malformed resource cannot break a scan that does not need it — the map only
   * makes MORE rules selectable, never fewer.
   */
  private static volatile Map<String, String> aliases;

  private LegacyRuleAliases() {}

  /**
   * The current id for a possibly-retired rule id.
   *
   * @param ruleId the id as written
   * @return the id the engine uses today, or {@code ruleId} unchanged when it is not retired
   */
  static String canonical(String ruleId) {
    if (ruleId == null || ruleId.isEmpty()) {
      return ruleId;
    }
    Map<String, String> map = aliases();
    if (map.isEmpty()) {
      return ruleId;
    }
    // Follow the chain, so a map that was generated in two steps still
    // resolves. The chain is bounded, because a cycle would otherwise hang.
    String current = ruleId;
    for (int i = 0; i < 8; i++) {
      String next = map.get(current);
      if (next == null || next.equals(current)) {
        return current;
      }
      current = next;
    }
    return current;
  }

  /** Whether a rule id is a retired one that the map knows about. */
  static boolean isRetired(String ruleId) {
    return ruleId != null && aliases().containsKey(ruleId);
  }

  /** The whole map, loaded once. */
  static Map<String, String> aliases() {
    Map<String, String> local = aliases;
    if (local != null) {
      return local;
    }
    synchronized (LegacyRuleAliases.class) {
      if (aliases != null) {
        return aliases;
      }
      Map<String, String> loaded = load();
      aliases = loaded;
      return loaded;
    }
  }

  private static Map<String, String> load() {
    Map<String, String> out = new HashMap<>();
    try (InputStream in = LegacyRuleAliases.class.getResourceAsStream(RESOURCE)) {
      if (in == null) {
        return out;
      }
      JsonNode root =
          new ObjectMapper().readTree(new String(in.readAllBytes(), StandardCharsets.UTF_8));
      java.util.Iterator<String> names = root.fieldNames();
      while (names.hasNext()) {
        String name = names.next();
        JsonNode value = root.get(name);
        if (value != null && value.isTextual()) {
          out.put(name, value.asText());
        }
      }
    } catch (IOException | RuntimeException e) {
      // A broken map must not break the scan. The map only ever makes MORE
      // rules selectable, so an empty map degrades to "the retired ids do
      // not resolve", which is the behaviour before the map existed.
      return new HashMap<>();
    }
    return out;
  }
}
