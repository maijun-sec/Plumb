package org.plumb.rules.framework;

import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.Map;
import java.util.Set;

/**
 * The catalogue of framework parameter-binding annotations.
 *
 * <p>A framework binds a request value to a method parameter BY ANNOTATION. A servlet-aware scanner
 * only knows {@code HttpServletRequest.getParameter(...)}, so in a Spring, JAX-RS, Quarkus or
 * Micronaut application it sees no source at all: the controller body never touches a request
 * object.
 *
 * <p>So "is this parameter attacker-controlled?" is a question about the ANNOTATION on it, and the
 * answer has to come from a catalogue of those annotations.
 *
 * <p>This class is that catalogue, and it is the ONLY copy. The taint engine (which decides where a
 * taint flow starts) and the input-validation checker (which demands that such a value be
 * validated) both read it.
 *
 * <p>Why one copy and not two: the two layers have to agree about what "user input" means. When
 * they each declared their own list, they drifted, and the drift was not symmetric. Thirteen
 * annotations were an HTTP trust boundary to the taint engine but invisible to the input-validation
 * checker -- so a {@code @RestQuery} parameter was tracked as attacker-controlled by one layer and
 * treated as trusted-by-default by the other. The reverse direction is just as bad: the taint
 * engine listed three annotation names that no framework defines at all, one of which ({@code
 * CookieValue2}) was a typo.
 *
 * <p>A single generated table cannot drift. This file is generated by {@code
 * scripts/gen_framework_annotations.py} from {@code scripts/framework_input_annotations.py}, where
 * every name is recorded together with the framework documentation it was checked against.
 */
public final class FrameworkInputAnnotations {

  /**
   * The framework a binding annotation belongs to.
   *
   * <p>Used to qualify a taint source label, so a finding names the trust boundary it crossed
   * ("spring-mvc") rather than only the annotation that bound it.
   */
  public static final String FRAMEWORK_SPRING_MVC = "spring-mvc";

  public static final String FRAMEWORK_JAX_RS = "jax-rs";
  public static final String FRAMEWORK_QUARKUS_REST = "quarkus-rest";
  public static final String FRAMEWORK_MICRONAUT = "micronaut";
  public static final String FRAMEWORK_JAKARTA_SERVLET = "jakarta-servlet";

  /**
   * Used when a binding annotation is present but no framework can be identified from the endpoint.
   */
  public static final String FRAMEWORK_UNKNOWN = "framework";

  /**
   * Every binding annotation, mapped to the framework that defines it.
   *
   * <p>Insertion order is the order the frameworks are reported in, so generated documentation and
   * test output read in a stable, grouped order.
   */
  private static final Map<String, String> ANNOTATION_TO_FRAMEWORK;

  /**
   * Annotations that mark a class or method as a framework endpoint, mapped to the framework they
   * identify.
   *
   * <p>The JAX-RS and Quarkus REST endpoint annotations are the SAME names ({@code @Path},
   * {@code @GET}, {@code @POST}, ...), so a bare name cannot tell them apart. The framework is then
   * inferred from the BINDING annotation on the parameter, which is unambiguous: {@code @RestQuery}
   * is Quarkus, {@code @QueryParam} is JAX-RS. The endpoint map is therefore only a hint, and the
   * binding annotation always wins.
   */
  private static final Map<String, String> FRAMEWORK_BY_ENDPOINT_ANNOTATION;

  static {
    Map<String, String> m = new LinkedHashMap<>();

    // --- Spring MVC / Spring Data ----------------------------------
    m.put("CookieValue", FRAMEWORK_SPRING_MVC);
    m.put("MatrixVariable", FRAMEWORK_SPRING_MVC);
    m.put("ModelAttribute", FRAMEWORK_SPRING_MVC);
    m.put("PathVariable", FRAMEWORK_SPRING_MVC);
    m.put("RequestAttribute", FRAMEWORK_SPRING_MVC);
    m.put("RequestBody", FRAMEWORK_SPRING_MVC);
    m.put("RequestHeader", FRAMEWORK_SPRING_MVC);
    m.put("RequestParam", FRAMEWORK_SPRING_MVC);
    m.put("RequestPart", FRAMEWORK_SPRING_MVC);
    m.put("SessionAttribute", FRAMEWORK_SPRING_MVC);

    // --- JAX-RS / Jakarta REST -------------------------------------
    m.put("BeanParam", FRAMEWORK_JAX_RS);
    m.put("CookieParam", FRAMEWORK_JAX_RS);
    m.put("FormParam", FRAMEWORK_JAX_RS);
    m.put("HeaderParam", FRAMEWORK_JAX_RS);
    m.put("MatrixParam", FRAMEWORK_JAX_RS);
    m.put("PathParam", FRAMEWORK_JAX_RS);
    m.put("QueryParam", FRAMEWORK_JAX_RS);

    // --- Quarkus REST (formerly RESTEasy Reactive) -----------------
    m.put("RestBeanParam", FRAMEWORK_QUARKUS_REST);
    m.put("RestCookie", FRAMEWORK_QUARKUS_REST);
    m.put("RestForm", FRAMEWORK_QUARKUS_REST);
    m.put("RestHeader", FRAMEWORK_QUARKUS_REST);
    m.put("RestMatrix", FRAMEWORK_QUARKUS_REST);
    m.put("RestPath", FRAMEWORK_QUARKUS_REST);
    m.put("RestQuery", FRAMEWORK_QUARKUS_REST);

    // --- Micronaut -------------------------------------------------
    m.put("Body", FRAMEWORK_MICRONAUT);
    m.put("Header", FRAMEWORK_MICRONAUT);
    m.put("Part", FRAMEWORK_MICRONAUT);
    m.put("QueryValue", FRAMEWORK_MICRONAUT);
    m.put("RequestBean", FRAMEWORK_MICRONAUT);

    // --- Jakarta Servlet (the annotation form) ---------------------
    m.put("WebParam", FRAMEWORK_JAKARTA_SERVLET);

    ANNOTATION_TO_FRAMEWORK = Collections.unmodifiableMap(m);

    Map<String, String> e = new LinkedHashMap<>();
    e.put("Controller", FRAMEWORK_MICRONAUT);
    e.put("DELETE", FRAMEWORK_JAX_RS);
    e.put("Delete", FRAMEWORK_MICRONAUT);
    e.put("DeleteMapping", FRAMEWORK_SPRING_MVC);
    e.put("GET", FRAMEWORK_JAX_RS);
    e.put("Get", FRAMEWORK_MICRONAUT);
    e.put("GetMapping", FRAMEWORK_SPRING_MVC);
    e.put("HEAD", FRAMEWORK_JAX_RS);
    e.put("Head", FRAMEWORK_MICRONAUT);
    e.put("OPTIONS", FRAMEWORK_JAX_RS);
    e.put("Options", FRAMEWORK_MICRONAUT);
    e.put("PATCH", FRAMEWORK_JAX_RS);
    e.put("POST", FRAMEWORK_JAX_RS);
    e.put("PUT", FRAMEWORK_JAX_RS);
    e.put("Patch", FRAMEWORK_MICRONAUT);
    e.put("PatchMapping", FRAMEWORK_SPRING_MVC);
    e.put("Path", FRAMEWORK_JAX_RS);
    e.put("Post", FRAMEWORK_MICRONAUT);
    e.put("PostMapping", FRAMEWORK_SPRING_MVC);
    e.put("Put", FRAMEWORK_MICRONAUT);
    e.put("PutMapping", FRAMEWORK_SPRING_MVC);
    e.put("RequestMapping", FRAMEWORK_SPRING_MVC);
    e.put("RestController", FRAMEWORK_SPRING_MVC);
    FRAMEWORK_BY_ENDPOINT_ANNOTATION = Collections.unmodifiableMap(e);
  }

  /**
   * Every annotation that binds a request value to a parameter.
   *
   * <p>Matched by SIMPLE NAME, which is what the IR records: {@code @RequestParam} and a
   * hypothetical {@code @org.acme.RequestParam} are the same name to this model.
   */
  public static final Set<String> USER_INPUT_PARAM_ANNOTATIONS =
      Collections.unmodifiableSet(new LinkedHashSet<>(ANNOTATION_TO_FRAMEWORK.keySet()));

  private FrameworkInputAnnotations() {}

  /**
   * Whether {@code annotation} binds a request value to a parameter.
   *
   * @param annotation the annotation's simple name, as the IR records it
   */
  public static boolean isUserInputAnnotation(String annotation) {
    return annotation != null && ANNOTATION_TO_FRAMEWORK.containsKey(annotation);
  }

  /**
   * The framework that defines {@code annotation}, or {@link #FRAMEWORK_UNKNOWN} when the
   * annotation is not a binding annotation or the framework cannot be identified.
   */
  public static String frameworkOf(String annotation) {
    String framework = ANNOTATION_TO_FRAMEWORK.get(annotation);
    return framework != null ? framework : FRAMEWORK_UNKNOWN;
  }

  /** The number of binding annotations in the catalogue. */
  public static int size() {
    return ANNOTATION_TO_FRAMEWORK.size();
  }

  /**
   * The framework an endpoint annotation identifies, or {@code null} when the annotation is not an
   * endpoint marker.
   *
   * <p>This is a HINT. {@code @Path} and {@code @GET} are shared by JAX-RS and Quarkus REST, so
   * this map cannot distinguish them. The binding annotation on the parameter always wins.
   */
  public static String frameworkOfEndpointAnnotation(String annotation) {
    return annotation == null ? null : FRAMEWORK_BY_ENDPOINT_ANNOTATION.get(annotation);
  }
}
