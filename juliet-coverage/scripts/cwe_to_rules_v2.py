"""
cwe_to_rules_v2.py — Map Juliet CWE → ACTUAL Plumb DFA rule ids.

The original cwe_to_rules.py used registry rule IDs (from --list-rules).
Those IDs do NOT match what the DFA engine actually emits in
findings. This version derives the mapping empirically from the
baseline scan output (`D:\tmp\plumb_test\scan\baseline\*.ndjson`).

Strategy: for each CWE dir, find the DFA rule ids that actually fire
on its positive test cases. The mapping is the union of those rule
ids. CWE without any positive hits (i.e. Plumb has no rule for it)
gets an empty list.

Usage:
  python cwe_to_rules_v2.py --all --out-dir D:\tmp\plumb_test\configs_v2
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path


# Plumb baseline dir — we read the actual emitted rule ids here.
BASELINE_DIR = Path(r"D:\tmp\plumb_test\scan\baseline")


def cwe_dirs(juliet_root: Path) -> list[str]:
    """Return sorted list of CWE dir stem names from the Juliet source tree."""
    out = []
    for d in sorted(juliet_root.glob("CWE*_*")):
        stem = d.name.split("_")[0]
        out.append(stem)
    return sorted(set(out))


def rules_for_cwe(cwe: str, baseline_dir: Path = BASELINE_DIR) -> list[str]:
    """Return the set of DFA rule ids that Plumb actually emits for this CWE.

    We exclude purely style / cosmetic rules (`pl-*`, `plumb.style.*`,
    `bu-*`) because those are not the rules a per-CWE whitelist should
    exercise — they produce noise unrelated to the CWE under test.
    """
    ndjson = baseline_dir / f"{cwe_to_dirname(cwe)}.ndjson"
    if not ndjson.exists() or ndjson.stat().st_size == 0:
        return []
    seen: set[str] = set()
    with open(ndjson, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            try:
                obj = json.loads(line)
            except Exception:
                continue
            rid = obj.get("rule_id") or ""
            if not rid:
                continue
            # Strip purely style / cosmetic ids
            if rid.startswith(("pl-", "bu-", "cov-", "plumb.style")):
                continue
            seen.add(rid)
    return sorted(seen)


def cwe_to_dirname(cwe: str) -> str | None:
    """Look up the actual dir name under baseline/ for a given CWE id."""
    matches = list(BASELINE_DIR.glob(f"{cwe}_*.ndjson"))
    return matches[0].stem if matches else None


def render_yaml(cwe_id: str, rules: list[str]) -> str:
    """Per-CWE YAML that whitelists the ACTUAL Plumb DFA rule ids
    that fire on positive Juliet test cases for that CWE."""
    out = [
        f"# Per-CWE YAML v2 for {cwe_id}",
        f"# Whitelist (DFA rule ids Plumb actually emits): {rules or '(none)'}",
        f"# Generated by cwe_to_rules_v2.py",
        f"# Strategy: whitelist by what Plumb's DFA engine emits, not",
        f"# what the RuleRegistry exposes via --list-rules.",
        "",
        "maxParallelism: 4",
        "cgStrategy: global",
        "aggressiveness: medium",
        "",
        "rules:",
        "  mode: whitelist",
        "  enabled:",
    ]
    if rules:
        for r in rules:
            out.append(f"    - {r}")
    else:
        out.append("    []")
    out += ["", "ai:", "  enabled: false"]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true", help="Generate YAMLs for all CWE")
    ap.add_argument("--cwe", type=str, help="Single CWE")
    ap.add_argument("--out-dir", type=Path, default=Path(r"D:\tmp\plumb_test\configs_v2"))
    ap.add_argument("--out", type=Path, help="Output file (single mode)")
    ap.add_argument("--juliet-root", type=Path, default=Path(r"D:\work\tmp\Juliet_Java\src\testcases"))
    args = ap.parse_args()

    if args.cwe:
        rules = rules_for_cwe(args.cwe)
        out = args.out or (args.out_dir / f"{args.cwe}.yaml")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(render_yaml(args.cwe, rules), encoding="utf-8")
        print(f"Wrote {out} (rules={rules})")
        return

    if args.all:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        cwes = cwe_dirs(args.juliet_root)
        n_with = 0
        n_without = 0
        for cwe in cwes:
            rules = rules_for_cwe(cwe)
            out = args.out_dir / f"{cwe}.yaml"
            out.write_text(render_yaml(cwe, rules), encoding="utf-8")
            if rules:
                n_with += 1
            else:
                n_without += 1
        print(f"Wrote {len(cwes)} YAMLs to {args.out_dir}")
        print(f"  with rules: {n_with}")
        print(f"  no rules (Plumb detected nothing): {n_without}")
        return

    ap.print_help()


if __name__ == "__main__":
    main()