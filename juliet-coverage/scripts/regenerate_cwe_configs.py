#!/usr/bin/env python3
"""Regenerate the per-CWE whitelist configs from the LIVE rule table.

WHY THIS REPLACES cwe_to_rules_v2.py

The old generator derived each CWE's whitelist from ONE PAST SCAN: the
rules that happened to fire on that CWE's directory on that day were
written into the config. That is circular. The whitelist decides which
rules run, and the scan of the whitelist decided the whitelist, so a CWE
whose rule did not fire in that one run was written down with a whitelist
that does not contain its own rule -- and could then never be measured.

The measurement says so plainly: 67 of the 112 CWEs have a rule the
engine ships and a config that does not enable it, so their coverage
number says nothing about the rule.

THE FIX

The whitelist comes from the engine's OWN rule table
(`--list-rule-cwes`, which reads the live registries): a rule belongs to
a CWE when the rule's own CWE label names it. That is a fact about the
engine, not about one run, so the derivation has no circularity.

A CWE keeps the COMMON rules it had before -- the ones that are not
about the CWE under test but whose findings are still worth recording
(the resource-leak rule, the unchecked-return rule, and so on) -- plus
the rules that are about this CWE.

    python regenerate_cwe_configs.py --rule-cwes <tsv> --out-dir <dir>
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
CONFIG_DIR = REPO / "juliet-coverage" / "configs"

# The rules that are NOT about any one CWE but whose findings the
# per-CWE measurements have always recorded. They stay: dropping them
# would change what a measurement means, and the measurement is a
# comparison over time.
#
# They are listed by their LIVE ids, so the config names a rule the
# engine actually emits.
COMMON_RULES = [
    "CatchGenericException",
    "InsecureCommunication",
    "UncheckedReturn",
    "plumb.resource.leak",
]

# The legacy spelling of each common rule, and the live id it resolves
# to. The config names the LIVE id, so a reader of the config can find
# the rule in the engine's own table without knowing the alias map.
#
# The old configs carried BOTH spellings for some rules -- a legacy id
# and the live id it resolves to. That is not a duplicate to the text
# but it IS a duplicate to the filter, and it made the config impossible
# to reason about: deleting one entry changed nothing, because the other
# still selected the rule.
LEGACY_TO_LIVE = {
    "CatchGenericException": "ast-error-catch-generic",
    "InsecureCommunication": "ast-security-insecure-communication",
    "UncheckedReturn": "ast-security-unchecked-return",
    "plumb.resource.leak": "dfa-taint-leak",
}


def norm_cwe(label: str) -> str:
    m = re.search(r"(\d+)", label or "")
    return m.group(1) if m else ""


def load_rule_cwes(path: Path) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    raw = path.read_bytes()
    text = None
    for enc in ("utf-8-sig", "utf-16", "utf-8"):
        try:
            text = raw.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    if text is None:
        return out
    for line in text.splitlines():
        parts = line.rstrip("\n").split("\t")
        if not parts or not parts[0]:
            continue
        out[parts[0].strip()] = [norm_cwe(c) for c in parts[1:] if c]
    return out


def read_existing(path: Path) -> tuple[str, list[str]]:
    """(mode, entries) of an existing config, so the rewrite preserves them."""
    mode = "whitelist"
    rules: list[str] = []
    in_enabled = False
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.rstrip()
        if not line.strip() or line.strip().startswith("#"):
            continue
        m = re.match(r"^\s*mode\s*:\s*(\w+)", line)
        if m:
            mode = m.group(1)
        if re.match(r"^\s*enabled\s*:", line):
            in_enabled = True
            continue
        if in_enabled:
            s = line.strip()
            if s.startswith("- "):
                rules.append(s[2:].strip())
                continue
            if s and not s.startswith("-"):
                in_enabled = False
    return mode, rules


def render(cwe: str, mode: str, rules: list[str]) -> str:
    out = [
        f"# Per-CWE YAML for CWE{cwe}",
        "#",
        "# The whitelist is derived from the engine's OWN rule table: a rule",
        "# belongs to this CWE when the rule's own CWE label names it. The",
        "# COMMON rules are the ones that are not about one CWE but whose",
        "# findings the measurement records anyway.",
        "#",
        "# Regenerated by juliet-coverage/scripts/regenerate_cwe_configs.py.",
        "# The previous version of this file was derived from ONE past scan,",
        "# which made the whitelist depend on the run it was supposed to",
        "# constrain -- a CWE whose rule had not fired yet could never be",
        "# measured.",
        "",
        "maxParallelism: 4",
        "cgStrategy: global",
        "aggressiveness: medium",
        "",
        "rules:",
        f"  mode: {mode}",
        "  enabled:",
    ]
    for r in rules:
        out.append(f"    - {r}")
    out += ["", "ai:", "  enabled: false"]
    return "\n".join(out) + "\n"


def select_key(entry: str, rule_cwes: dict[str, list[str]]) -> str:
    """The rule an entry selects, so two spellings of one rule collapse.

    The alias table is the engine's own map from a retired id to the id
    it was renamed to. Two entries that resolve to the same live rule
    are the SAME entry written twice.
    """
    canonical = ALIASES.get(entry, entry)
    if canonical in rule_cwes:
        return canonical
    # The entry may be a legacy NAME that the alias map resolves to a
    # live id that is itself in the table.
    return canonical


ALIASES: dict[str, str] = {}


def load_aliases() -> None:
    global ALIASES
    p = REPO / "plumb-main" / "src" / "main" / "resources" / "legacy-rule-aliases.json"
    if p.is_file():
        ALIASES = json.loads(p.read_text(encoding="utf-8"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rule-cwes", required=True,
                    help="the engine's --list-rule-cwes output")
    ap.add_argument("--out-dir", default=str(CONFIG_DIR))
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--cwes", nargs="*")
    args = ap.parse_args()

    rule_cwes = load_rule_cwes(Path(args.rule_cwes))
    load_aliases()
    rules_for_cwe: dict[str, list[str]] = {}
    for rid, cwes in rule_cwes.items():
        for c in cwes:
            rules_for_cwe.setdefault(c, []).append(rid)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    changed = 0
    for cfg in sorted(CONFIG_DIR.glob("CWE*.yaml")):
        cwe = cfg.stem[3:]
        if args.cwes and cwe not in args.cwes:
            continue
        mode, existing = read_existing(cfg)
        if mode == "all":
            # A `mode: all` config is a deliberate no-whitelist
            # measurement; it is not regenerated.
            continue
        own = sorted(rules_for_cwe.get(cwe, []))
        # The common rules are named by their LIVE id, so the config
        # names a rule the reader can find in the engine's own table.
        common = [LEGACY_TO_LIVE[r] for r in COMMON_RULES
                  if r in existing or LEGACY_TO_LIVE[r] in existing]
        # The rules the previous config had that are neither common nor
        # about this CWE are kept too: dropping them silently would
        # change what the measurement covers.
        extra = [r for r in existing if r not in common and r not in own]
        # The extra entries are named by their LIVE id too, so a reader
        # can find every rule in the engine's own table.
        extra = [ALIASES.get(r, r) for r in extra]
        # DEDUPLICATE BY THE RULE, NOT BY THE TEXT.
        #
        # The old configs carried both a legacy id and the live id it
        # resolves to -- two different strings, one rule. Deleting one
        # of them changed nothing, because the other still selected the
        # rule, and a reader could not tell which entry was the real
        # one. So the entries are deduplicated by the rule they select.
        ordered: list[str] = []
        selected: set[str] = set()
        for r in common + own + extra:
            key = select_key(r, rule_cwes)
            if key in selected:
                continue
            selected.add(key)
            ordered.append(r)
        text = render(cwe, mode, ordered)
        old = cfg.read_text(encoding="utf-8", errors="replace")
        new_path = out_dir / cfg.name
        if old != text:
            changed += 1
            if not args.dry_run:
                new_path.write_text(text, encoding="utf-8")
        print("CWE-%-4s own=%d common=%d total=%d%s"
              % (cwe, len(own), len(common), len(ordered),
                 "  (changed)" if old != text else ""))
    print()
    print("%d configs would change" % changed)
    return 0


if __name__ == "__main__":
    sys.exit(main())
