#!/usr/bin/env python3
"""Generate FrameworkInputAnnotations.java from the verified catalogue.

The source of truth is scripts/framework_input_annotations.py, where every
annotation name is recorded together with the framework documentation it was
checked against. This script renders that into Java.

    python scripts/gen_framework_annotations.py           # write the file
    python scripts/gen_framework_annotations.py --check   # verify it is current

The generated Java must be ALREADY FORMATTED, so that the generator's
check and the format gate agree instead of fighting each other. That is
the same rule the category generator follows.
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from framework_input_annotations import (  # noqa: E402
    ANNOTATIONS,
    CONTAINER_ANNOTATIONS,
    ENDPOINT_ANNOTATIONS,
    FRAMEWORKS,
)
from _formatter import format_source  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(
    REPO, "plumb-rules", "src", "main", "java", "org", "plumb", "rules",
    "framework", "FrameworkInputAnnotations.java")

FRAMEWORK_CONSTANTS = {
    "spring-mvc": "FRAMEWORK_SPRING_MVC",
    "jax-rs": "FRAMEWORK_JAX_RS",
    "quarkus-rest": "FRAMEWORK_QUARKUS_REST",
    "micronaut": "FRAMEWORK_MICRONAUT",
    "jakarta-servlet": "FRAMEWORK_JAKARTA_SERVLET",
}

GROUP_TITLES = {
    "spring-mvc": "Spring MVC / Spring Data",
    "jax-rs": "JAX-RS / Jakarta REST",
    "quarkus-rest": "Quarkus REST (formerly RESTEasy Reactive)",
    "micronaut": "Micronaut",
    "jakarta-servlet": "Jakarta Servlet (the annotation form)",
}


def render():
    lines = []
    add = lines.append
    add("package org.plumb.rules.framework;")
    add("")
    add("import java.util.Collections;")
    add("import java.util.LinkedHashMap;")
    add("import java.util.LinkedHashSet;")
    add("import java.util.Map;")
    add("import java.util.Set;")
    add("")
    add("/**")
    add(" * The catalogue of framework parameter-binding annotations.")
    add(" *")
    add(" * <p>A framework binds a request value to a method parameter BY ANNOTATION. A servlet-aware scanner")
    add(" * only knows {@code HttpServletRequest.getParameter(...)}, so in a Spring, JAX-RS, Quarkus or Micronaut")
    add(" * application it sees no source at all: the controller body never touches a request object.")
    add(" *")
    add(" * <p>So \"is this parameter attacker-controlled?\" is a question about the ANNOTATION on it, and the")
    add(" * answer has to come from a catalogue of those annotations.")
    add(" *")
    add(" * <p>This class is that catalogue, and it is the ONLY copy. The taint engine (which decides where a")
    add(" * taint flow starts) and the input-validation checker (which demands that such a value be validated)")
    add(" * both read it.")
    add(" *")
    add(" * <p>Why one copy and not two: the two layers have to agree about what \"user input\" means. When they")
    add(" * each declared their own list, they drifted, and the drift was not symmetric. Thirteen annotations")
    add(" * were an HTTP trust boundary to the taint engine but invisible to the input-validation checker -- so a")
    add(" * {@code @RestQuery} parameter was tracked as attacker-controlled by one layer and treated as")
    add(" * trusted-by-default by the other. The reverse direction is just as bad: the taint engine listed three")
    add(" * annotation names that no framework defines at all, one of which ({@code CookieValue2}) was a typo.")
    add(" *")
    add(" * <p>A single generated table cannot drift. This file is generated by")
    add(" * {@code scripts/gen_framework_annotations.py} from {@code scripts/framework_input_annotations.py}, where")
    add(" * every name is recorded together with the framework documentation it was checked against.")
    add(" */")
    add("public final class FrameworkInputAnnotations {")
    add("")
    add("  /**")
    add("   * The framework a binding annotation belongs to.")
    add("   *")
    add("   * <p>Used to qualify a taint source label, so a finding names the trust boundary it crossed")
    add("   * (\"spring-mvc\") rather than only the annotation that bound it.")
    add("   */")
    for framework in FRAMEWORKS:
        add("  public static final String %s = \"%s\";" % (
            FRAMEWORK_CONSTANTS[framework], framework))
    add("")
    add("  /** Used when a binding annotation is present but no framework can be identified from the endpoint. */")
    add("  public static final String FRAMEWORK_UNKNOWN = \"framework\";")
    add("")
    add("  /**")
    add("   * Every binding annotation, mapped to the framework that defines it.")
    add("   *")
    add("   * <p>Insertion order is the order the frameworks are reported in, so generated documentation and")
    add("   * test output read in a stable, grouped order.")
    add("   */")
    add("  private static final Map<String, String> ANNOTATION_TO_FRAMEWORK;")
    add("")
    add("  /**")
    add("   * Annotations that mark a class or method as a framework endpoint, mapped to the framework they")
    add("   * identify.")
    add("   *")
    add("   * <p>The JAX-RS and Quarkus REST endpoint annotations are the SAME names ({@code @Path}, {@code")
    add("   * @GET}, {@code @POST}, ...), so a bare name cannot tell them apart. The framework is then")
    add("   * inferred from the BINDING annotation on the parameter, which is unambiguous: {@code @RestQuery}")
    add("   * is Quarkus, {@code @QueryParam} is JAX-RS. The endpoint map is therefore only a hint, and the")
    add("   * binding annotation always wins.")
    add("   */")
    add("  private static final Map<String, String> FRAMEWORK_BY_ENDPOINT_ANNOTATION;")
    add("")
    add("  /**")
    add("   * Annotations that bind a CONTAINER of values rather than a single value, mapped to the framework")
    add("   * that defines them.")
    add("   *")
    add("   * <p>A bean parameter is not itself the request value: the framework binds each FIELD of the bean")
    add("   * class to its own request value, so the binding annotation lives on the bean's FIELD:")
    add("   *")
    add("   * <pre>")
    add("   *   public class Parameters {")
    add("   *     &#64;RestQuery(\"customer\")")
    add("   *     public String customer;")
    add("   *   }")
    add("   *")
    add("   *   public void search(&#64;RestBeanParam Parameters params) {")
    add("   *     repository.findByCustomer(params.customer);")
    add("   *   }")
    add("   * </pre>")
    add("   *")
    add("   * <p>The parameter is a CARRIER, and the fields it carries are the sources. The taint engine has to")
    add("   * read the FIELD's annotation to learn where the value came from.")
    add("   */")
    add("  private static final Map<String, String> CONTAINER_TO_FRAMEWORK;")
    add("")
    add("  static {")
    add("    Map<String, String> m = new LinkedHashMap<>();")
    add("")
    for framework in FRAMEWORKS:
        add("    // --- %s %s" % (GROUP_TITLES[framework], "-" * max(1, 58 - len(GROUP_TITLES[framework]))))
        for name in sorted(n for n, (f, _) in ANNOTATIONS.items() if f == framework):
            add('    m.put("%s", %s);' % (name, FRAMEWORK_CONSTANTS[framework]))
        add("")
    add("    ANNOTATION_TO_FRAMEWORK = Collections.unmodifiableMap(m);")
    add("")
    add("    Map<String, String> c = new LinkedHashMap<>();")
    for name in sorted(CONTAINER_ANNOTATIONS):
        add('    c.put("%s", %s);' % (
            name, FRAMEWORK_CONSTANTS[CONTAINER_ANNOTATIONS[name]]))
    add("    CONTAINER_TO_FRAMEWORK = Collections.unmodifiableMap(c);")
    add("")
    add("    Map<String, String> e = new LinkedHashMap<>();")
    for name in sorted(ENDPOINT_ANNOTATIONS):
        add('    e.put("%s", %s);' % (name, FRAMEWORK_CONSTANTS[ENDPOINT_ANNOTATIONS[name]]))
    add("    FRAMEWORK_BY_ENDPOINT_ANNOTATION = Collections.unmodifiableMap(e);")
    add("  }")
    add("")
    add("  /**")
    add("   * Every annotation that binds a request value to a parameter.")
    add("   *")
    add("   * <p>Matched by SIMPLE NAME, which is what the IR records: {@code @RequestParam} and a hypothetical")
    add("   * {@code @org.acme.RequestParam} are the same name to this model.")
    add("   */")
    add("  public static final Set<String> USER_INPUT_PARAM_ANNOTATIONS =")
    add("      Collections.unmodifiableSet(new LinkedHashSet<>(ANNOTATION_TO_FRAMEWORK.keySet()));")
    add("")
    add("  private FrameworkInputAnnotations() {}")
    add("")
    add("  /**")
    add("   * Whether {@code annotation} binds a request value to a parameter.")
    add("   *")
    add("   * @param annotation the annotation's simple name, as the IR records it")
    add("   */")
    add("  public static boolean isUserInputAnnotation(String annotation) {")
    add("    return annotation != null && ANNOTATION_TO_FRAMEWORK.containsKey(annotation);")
    add("  }")
    add("")
    add("  /**")
    add("   * The framework that defines {@code annotation}, or {@link #FRAMEWORK_UNKNOWN} when the annotation is")
    add("   * not a binding annotation or the framework cannot be identified.")
    add("   */")
    add("  public static String frameworkOf(String annotation) {")
    add("    String framework = ANNOTATION_TO_FRAMEWORK.get(annotation);")
    add("    return framework != null ? framework : FRAMEWORK_UNKNOWN;")
    add("  }")
    add("")
    add("  /** The number of binding annotations in the catalogue. */")
    add("  public static int size() {")
    add("    return ANNOTATION_TO_FRAMEWORK.size();")
    add("  }")
    add("")
    add("  /**")
    add("   * Every annotation that binds a CONTAINER of request values to a parameter.")
    add("   *")
    add("   * <p>Matched by SIMPLE NAME, like {@link #USER_INPUT_PARAM_ANNOTATIONS}.")
    add("   */")
    add("  public static final Set<String> CONTAINER_BINDING_ANNOTATIONS =")
    add("      Collections.unmodifiableSet(new LinkedHashSet<>(CONTAINER_TO_FRAMEWORK.keySet()));")
    add("")
    add("  /**")
    add("   * Whether {@code annotation} binds a container of request values to a parameter.")
    add("   *")
    add("   * @param annotation the annotation's simple name, as the IR records it")
    add("   */")
    add("  public static boolean isContainerAnnotation(String annotation) {")
    add("    return annotation != null && CONTAINER_TO_FRAMEWORK.containsKey(annotation);")
    add("  }")
    add("")
    add("  /**")
    add("   * The framework that defines the container annotation {@code annotation}, or {@link")
    add("   * #FRAMEWORK_UNKNOWN} when it is not a container annotation.")
    add("   */")
    add("  public static String frameworkOfContainerAnnotation(String annotation) {")
    add("    String framework = CONTAINER_TO_FRAMEWORK.get(annotation);")
    add("    return framework != null ? framework : FRAMEWORK_UNKNOWN;")
    add("  }")
    add("")
    add("  /**")
    add("   * The framework an endpoint annotation identifies, or {@code null} when the annotation is not an")
    add("   * endpoint marker.")
    add("   *")
    add("   * <p>This is a HINT. {@code @Path} and {@code @GET} are shared by JAX-RS and Quarkus REST, so this")
    add("   * map cannot distinguish them. The binding annotation on the parameter always wins.")
    add("   */")
    add("  public static String frameworkOfEndpointAnnotation(String annotation) {")
    add("    return annotation == null ? null : FRAMEWORK_BY_ENDPOINT_ANNOTATION.get(annotation);")
    add("  }")
    add("}")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    rendered = render()

    # Format the rendered text so the generated file is formatter-clean.
    jar = None
    from _formatter import formatter_jar
    try:
        jar = formatter_jar()
    except Exception as exc:  # noqa: BLE001
        print("FAILED to obtain the formatter: %s" % exc)
        return 2
    formatted = format_source(jar, rendered, "FrameworkInputAnnotations.java")

    current = None
    if os.path.isfile(TARGET):
        with open(TARGET, "r", encoding="utf-8", newline="") as fh:
            current = fh.read()

    if check:
        if current == formatted:
            print("OK: %s is up to date (%d annotations)" % (
                os.path.relpath(TARGET, REPO).replace(os.sep, "/"), len(ANNOTATIONS)))
            return 0
        print("STALE: %s does not match the catalogue" % (
            os.path.relpath(TARGET, REPO).replace(os.sep, "/")))
        return 1

    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="") as fh:
        fh.write(formatted)
    print("Wrote %s (%d annotations across %d frameworks)" % (
        os.path.relpath(TARGET, REPO).replace(os.sep, "/"), len(ANNOTATIONS), len(FRAMEWORKS)))
    return 0


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    sys.exit(main())
