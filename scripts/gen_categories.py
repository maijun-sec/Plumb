#!/usr/bin/env python3
"""
Regenerate `plumb-style/src/main/java/org/plumb/style/CheckerCategories.java`.

The generated file is the simple-class-name -> category map that
`AstCheckerRegistry.byCategory(...)` consults. It cannot be recovered from the
compiled classpath (Maven flattens every class into one package directory), so
it is baked at build time by this script.

The category of a checker is its subdirectory under
`plumb-style/src/main/java/org/plumb/style/`:

    bug  concurrency  design  error  naming  performance  quality  security  style

A checker that lives directly in the package root (there is one:
`ObjectHijackCheck`) has no category and is NOT emitted - `byCategory(...)`
cannot select it. Use `load("<glob>")` or `register(...)` for those.

Usage:
    python scripts/gen_categories.py            # rewrite the file in place
    python scripts/gen_categories.py --check    # fail if the file is stale
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _formatter import format_source, formatter_jar  # noqa: E402
from license_header import header_text  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
STYLE_ROOT = ROOT / "plumb-style/src/main/java/org/plumb/style"
OUT = STYLE_ROOT / "CheckerCategories.java"

# Subdirectories that actually hold checkers. `annotations/` and `config/`
# hold annotation-IR helpers, not checkers.
CATEGORIES = [
    "bug",
    "concurrency",
    "design",
    "error",
    "naming",
    "performance",
    "quality",
    "security",
    "style",
]

CLASS_RE = re.compile(
    r"public\s+(?:final\s+|abstract\s+)?class\s+(\w+)\s+implements\s+AstChecker\b"
)
# A checker may extend an abstract base (e.g. AbstractNamingCheck) instead.
EXTENDS_RE = re.compile(
    r"public\s+(?:final\s+|abstract\s+)?class\s+(\w+)\s+extends\s+\w*AstChecker\b"
)
# Classes that are not checkers even though they live under a category dir.
NOT_A_CHECKER = {"AstCheckerRegistry", "CheckerCategories"}


def collect() -> dict[str, str]:
    """Return {simple class name: category} for every checker under STYLE_ROOT."""
    out: dict[str, str] = {}
    for category in CATEGORIES:
        directory = STYLE_ROOT / category
        if not directory.is_dir():
            continue
        for path in sorted(directory.glob("*.java")):
            if path.name in NOT_A_CHECKER:
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            m = CLASS_RE.search(text) or EXTENDS_RE.search(text)
            if not m:
                continue
            out[m.group(1)] = category
    return out


def render(entries: dict[str, str]) -> str:
    lines: list[str] = []
    # The licence header comes from scripts/license_header.py, which is
    # the single source of truth for the text. The generated file is
    # still a source file that ships, so it carries the header like
    # every other one -- and because the header is emitted HERE
    # rather than pasted in by hand, regenerating the file cannot
    # drop it and the licence gate cannot drift away from it.
    lines.append(header_text().rstrip("\n"))
    lines.append("// AUTO-GENERATED by scripts/gen_categories.py — DO NOT EDIT.")
    lines.append("// Run scripts/gen_categories.py to regenerate.")
    lines.append("package org.plumb.style;")
    lines.append("")
    lines.append("import java.util.LinkedHashMap;")
    lines.append("import java.util.Map;")
    lines.append("")
    lines.append("final class CheckerCategories {")
    lines.append("  private CheckerCategories() {}")
    lines.append("")
    lines.append("  /**")
    lines.append(
        "   * Simple class name -> subdirectory category. Categories: "
        + ", ".join(CATEGORIES)
        + "."
    )
    lines.append("   */")
    lines.append("  static final Map<String, String> CHECKER_CATEGORIES = build();")
    lines.append("")
    lines.append("  private static Map<String, String> build() {")
    lines.append("    Map<String, String> m = new LinkedHashMap<>();")
    for name in sorted(entries):
        lines.append(f'    m.put("{name}", "{entries[name]}");')
    lines.append("    return m;")
    lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_formatted(entries: dict[str, str]) -> str:
    """Render the file the way the formatter would write it.

    The generator compares its output against the file on disk, byte for
    byte. If it emitted unformatted code, the format gate and this
    generator would fight: the generator writes unformatted code, the
    formatter rewrites it, and `--check` fails again. Emitting FORMATTED
    code makes the two agree.
    """
    raw = render(entries)
    try:
        jar = formatter_jar()
    except Exception as exc:  # noqa: BLE001
        print(f"ERROR: could not obtain the formatter: {exc}", file=sys.stderr)
        raise
    return format_source(jar, raw, "CheckerCategories.java")


def main() -> int:
    entries = collect()
    if not entries:
        print("ERROR: no checkers found - is the path right?", file=sys.stderr)
        return 1
    new_text = render_formatted(entries)
    old_text = OUT.read_text(encoding="utf-8") if OUT.exists() else ""

    if "--check" in sys.argv:
        if old_text != new_text:
            print(f"STALE: {OUT.relative_to(ROOT)} is out of date.", file=sys.stderr)
            print(
                f"  on disk: {old_text.count('m.put(')} entries; "
                f"expected: {len(entries)} entries",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {OUT.relative_to(ROOT)} is up to date ({len(entries)} entries)")
        return 0

    OUT.write_text(new_text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}  ({len(entries)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
